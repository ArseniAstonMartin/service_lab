    JOIN service              sv ON sv.name = v.service_name
) src
ON (tgt.entry_id = src.entry_id AND tgt.service_id = src.service_id)
WHEN NOT MATCHED THEN INSERT (entry_id, service_id)
    VALUES (src.entry_id, src.service_id);


