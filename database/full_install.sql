        SELECT 'Toyota',         'Tacoma',           2012,        'BCM',                                 'BCM-0000',                'IMPORT'                     FROM dual
    ) v
    JOIN vehicle_ref     vr ON vr.make = v.make AND vr.model = v.model AND vr.year = v.year
