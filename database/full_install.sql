    -- p_entry_id -- never raises for either case, since a page/report
    -- source should not itself blow up on empty data.
    -- ------------------------------------------------------------------------
    FUNCTION get_services(p_entry_id IN NUMBER) RETURN t_service_tab PIPELINED;

