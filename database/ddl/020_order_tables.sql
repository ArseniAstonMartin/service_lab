CREATE INDEX ix_orders_email_lower ON orders (LOWER(customer_email));
CREATE INDEX ix_orders_status ON orders (status);
CREATE INDEX ix_orders_vehicle ON orders (vehicle_id);
CREATE INDEX ix_orders_category ON orders (category_id);
CREATE INDEX ix_orders_matched_entry ON orders (matched_entry_id);
