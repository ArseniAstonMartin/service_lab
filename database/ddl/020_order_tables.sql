-- ----------------------------------------------------------------------------
-- ORDER_PHOTO
-- Sticker/label photo (required at submission), plus DONOR/ORIGINAL photos
-- for cloning orders (PRD 4.4).
-- ----------------------------------------------------------------------------
CREATE TABLE order_photo (
    photo_id      NUMBER          GENERATED BY DEFAULT AS IDENTITY
                                   (START WITH 1 INCREMENT BY 1) NOT NULL,
    order_id      NUMBER          NOT NULL,
    photo_type    VARCHAR2(20)    NOT NULL,
    photo_blob    BLOB            NOT NULL,
    uploaded_at   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_order_photo PRIMARY KEY (photo_id),
    CONSTRAINT fk_order_photo_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE CASCADE
    -- CK_ORDER_PHOTO_TYPE (PHOTO_TYPE IN ('STICKER','DONOR','ORIGINAL')) is
    -- added in 040_constraints.sql (TASK-006).
);

COMMENT ON TABLE order_photo IS 'Photos uploaded for an order: STICKER (the required label photo), DONOR/ORIGINAL (cloning orders, PRD 4.4). Populated via pkg_security.store_order_photo (TASK-011) from APEX_APPLICATION_TEMP_FILES.';

CREATE INDEX ix_order_photo_order ON order_photo (order_id);

-- ----------------------------------------------------------------------------
-- ORDER_ANSWER
-- Answers to the dynamic, service-driven question set (PRD 4.4 / TASK-020).
-- ----------------------------------------------------------------------------
CREATE TABLE order_answer (
    answer_id       NUMBER          GENERATED BY DEFAULT AS IDENTITY
                                     (START WITH 1 INCREMENT BY 1) NOT NULL,
    order_id        NUMBER          NOT NULL,
    question_code   VARCHAR2(50)    NOT NULL,
    answer_value    VARCHAR2(4000),
    CONSTRAINT pk_order_answer PRIMARY KEY (answer_id),
    CONSTRAINT fk_order_answer_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE CASCADE,
    CONSTRAINT uq_order_answer_question UNIQUE (order_id, question_code)
);

COMMENT ON TABLE order_answer IS 'One row per (order, question_code) answer to the dynamic question set defined by QUESTION_DEF (TASK-005) for the order''s selected service''s QUESTION_SET_CODE.';

CREATE INDEX ix_order_answer_order ON order_answer (order_id);

-- ----------------------------------------------------------------------------
-- ORDER_STATUS_HISTORY
-- Full audit trail of every status change, written exclusively by
-- pkg_order_status (TASK-012).
-- ----------------------------------------------------------------------------
CREATE TABLE order_status_history (
    history_id    NUMBER          GENERATED BY DEFAULT AS IDENTITY
                                   (START WITH 1 INCREMENT BY 1) NOT NULL,
    order_id      NUMBER          NOT NULL,
    status        VARCHAR2(30)    NOT NULL,
    changed_at    TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    changed_by    VARCHAR2(50)    NOT NULL,
    CONSTRAINT pk_order_status_history PRIMARY KEY (history_id),
    CONSTRAINT fk_order_status_history_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id) ON DELETE CASCADE
);

COMMENT ON TABLE order_status_history IS 'Append-only audit trail of ORDERS.STATUS transitions. CHANGED_BY is the admin username (APP_USER), or SYSTEM for webhook/automated transitions. Written only by pkg_order_status.change_status (TASK-012); a trigger on ORDERS (TASK-006) rejects any STATUS change that does not go through that package.';

CREATE INDEX ix_order_status_history_order ON order_status_history (order_id, changed_at);
